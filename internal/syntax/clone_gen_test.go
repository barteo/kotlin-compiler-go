var updateClone = flag.Bool("update-clone", false, "rewrite clone_gen.go")

// TestCloneGenerated checks that clone_gen.go is what cloneSource makes of
// the package's types; -update-clone rewrites it.
func TestCloneGenerated(t *testing.T) {
	src, err := cloneSource()
	if err != nil {
		t.Fatal(err)
	}
	old, _ := os.ReadFile("clone_gen.go")
	if bytes.Equal(old, src) {
		return
	}
	if *updateClone {
		if err := os.WriteFile("clone_gen.go", src, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	t.Fatal("clone_gen.go is out of date: go test ./internal/syntax -run TestCloneGenerated -update-clone")
}

// cloneSource type-checks the package's non-test sources and writes a
// clone method for each of its struct types that File reaches: one that
// copies the node and everything it owns, as clone.go describes.
func cloneSource() ([]byte, error) {
	fset := gotoken.NewFileSet()
	pkgs, err := goparser.ParseDir(fset, ".", func(fi os.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go") && fi.Name() != "clone_gen.go"
	}, 0)
	if err != nil {
		return nil, err
	}
	var files []*goast.File
	for _, f := range pkgs["syntax"].Files {
		files = append(files, f)
	}
	sort.Slice(files, func(i, j int) bool { return fset.File(files[i].Pos()).Name() < fset.File(files[j].Pos()).Name() })
	conf := gotypes.Config{Importer: goimporter.ForCompiler(fset, "source", nil), Error: func(error) {}}
	pkg, _ := conf.Check("github.com/barteo/kotlin-compiler-go/internal/syntax", fset, files, nil)
	g := &cloneGen{pkg: pkg, structs: map[*gotypes.Named]bool{}}
	// The struct types that implement each interface the AST holds.
	for _, name := range pkg.Scope().Names() {
		tn, ok := pkg.Scope().Lookup(name).(*gotypes.TypeName)
		if !ok || tn.IsAlias() {
			continue
		}
		if n, ok := tn.Type().(*gotypes.Named); ok {
			if _, ok := n.Underlying().(*gotypes.Struct); ok {
				g.all = append(g.all, n)
			}
		}
	}
	g.need(pkg.Scope().Lookup("File").Type())
	var names []*gotypes.Named
	for n := range g.structs {
		names = append(names, n)
	}
	sort.Slice(names, func(i, j int) bool { return names[i].Obj().Name() < names[j].Obj().Name() })
	fmt.Fprintf(&g.b, "// Code generated by TestCloneGenerated (clone_gen_test.go); DO NOT EDIT.\n\npackage syntax\n\nimport (\n\t\"fmt\"\n\t\"maps\"\n\t\"slices\"\n)\n\nvar _ = maps.Clone[map[int]int]\n\n")
	for _, n := range names {
		g.method(n)
	}
	for _, it := range g.ifaces {
		g.iface(it)
	}
	return goformat.Source(g.b.Bytes())
}

type cloneGen struct {
	pkg     *gotypes.Package
	all     []*gotypes.Named // the package's struct types
	structs map[*gotypes.Named]bool
	ifaces  []*gotypes.Named
	b       bytes.Buffer
}

func (g *cloneGen) local(t gotypes.Type) (*gotypes.Named, bool) {
	n, ok := t.(*gotypes.Named)
	return n, ok && n.Obj().Pkg() == g.pkg
}

// need notes the struct types and interfaces t reaches.
func (g *cloneGen) need(t gotypes.Type) {
	switch t := gotypes.Unalias(t).(type) {
	case *gotypes.Pointer:
		g.need(t.Elem())
	case *gotypes.Slice:
		g.need(t.Elem())
	case *gotypes.Map:
		g.need(t.Key())
		g.need(t.Elem())
	case *gotypes.Named:
		n, ok := g.local(t)
		if !ok {
			return
		}
		switch u := n.Underlying().(type) {
		case *gotypes.Struct:
			if g.structs[n] {
				return
			}
			g.structs[n] = true
			for i := range u.NumFields() {
				g.need(u.Field(i).Type())
			}
		case *gotypes.Interface:
			for _, it := range g.ifaces {
				if it == n {
					return
				}
			}
			g.ifaces = append(g.ifaces, n)
			for _, s := range g.impls(u) {
				g.need(s)
			}
		default:
			g.need(u)
		}
	case *gotypes.Interface:
		// any: the keys of File.Annotated, nodes of the tree.
		for _, s := range g.impls(t) {
			g.need(s)
		}
	}
}

// impls returns the pointers to the package's struct types that
// implement interface it; for any, those of Stmt and Expr.
func (g *cloneGen) impls(it *gotypes.Interface) []*gotypes.Named {
	var r []*gotypes.Named
	for _, n := range g.all {
		if it.Empty() {
			if !gotypes.Implements(gotypes.NewPointer(n), g.pkg.Scope().Lookup("Stmt").Type().Underlying().(*gotypes.Interface)) &&
				!gotypes.Implements(gotypes.NewPointer(n), g.pkg.Scope().Lookup("Expr").Type().Underlying().(*gotypes.Interface)) {
				continue
			}
		} else if !gotypes.Implements(gotypes.NewPointer(n), it) {
			continue
		}
		r = append(r, n)
	}
	return r
}

func (g *cloneGen) typeName(t gotypes.Type) string {
	return gotypes.TypeString(t, func(p *gotypes.Package) string {
		if p == g.pkg {
			return ""
		}
		return p.Name()
	})
}

// method writes clone<T>, which copies a *T, and fix<T>, which makes a
// copied T's fields its own.
func (g *cloneGen) method(n *gotypes.Named) {
	name := n.Obj().Name()
	fmt.Fprintf(&g.b, "func (c *cloner) clone%s(x *%s) *%s {\n\tif x == nil {\n\t\treturn nil\n\t}\n", name, name, name)
	fmt.Fprintf(&g.b, "\tif c.memo != nil {\n\t\tif y, ok := c.memo[x]; ok {\n\t\t\tc.hits++\n\t\t\treturn y.(*%s)\n\t\t}\n\t}\n", name)
	fmt.Fprintf(&g.b, "\ty := new(%s)\n\t*y = *x\n\tif c.memo != nil {\n\t\tc.memo[x] = y\n\t}\n\tc.fix%s(y)\n\treturn y\n}\n\n", name, name)
	fmt.Fprintf(&g.b, "func (c *cloner) fix%s(y *%s) {\n", name, name)
	s := n.Underlying().(*gotypes.Struct)
	for i := range s.NumFields() {
		f := s.Field(i)
		if code := g.value("y."+f.Name(), f.Type(), 1); code != "" {
			g.b.WriteString(code)
		}
	}
	g.b.WriteString("}\n\n")
}

// value returns the statements that make the copied value at lhs, of
// type t, its own, or "" if a shallow copy is all it needs: a basic
// value, or a value of another package's type (the checker's symbols
// and types, which a lowered tree doesn't hold yet).
func (g *cloneGen) value(lhs string, t gotypes.Type, depth int) string {
	switch t := gotypes.Unalias(t).(type) {
	case *gotypes.Basic:
		return ""
	case *gotypes.Pointer:
		if n, ok := g.local(t.Elem()); ok {
			if _, ok := n.Underlying().(*gotypes.Struct); ok {
				return fmt.Sprintf("%s = c.clone%s(%s)\n", lhs, n.Obj().Name(), lhs)
			}
			panic("clone: unhandled pointer " + t.String())
		}
		return ""
	case *gotypes.Slice:
		inner := g.value(fmt.Sprintf("%s[i%d]", lhs, depth), t.Elem(), depth+1)
		if inner == "" {
			return fmt.Sprintf("%s = slices.Clone(%s)\n", lhs, lhs)
		}
		return fmt.Sprintf("if %s != nil {\n%s = slices.Clone(%s)\nfor i%d := range %s {\n%s}\n}\n", lhs, lhs, lhs, depth, lhs, inner)
	case *gotypes.Map:
		k, v := fmt.Sprintf("k%d", depth), fmt.Sprintf("v%d", depth)
		kc, vc := g.value(k, t.Key(), depth+1), g.value(v, t.Elem(), depth+1)
		if kc == "" && vc == "" {
			return fmt.Sprintf("%s = maps.Clone(%s)\n", lhs, lhs)
		}
		if _, ok := gotypes.Unalias(t.Key()).(*gotypes.Interface); ok {
			// Nodes as keys: the copies' keys are the nodes' copies,
			// once the whole tree is copied (cloner.keys).
			kc = ""
		}
		return fmt.Sprintf("if %s != nil {\nm%d := make(%s, len(%s))\nfor %s, %s := range %s {\n%s%sm%d[%s] = %s\n}\n%s = m%d\n", lhs, depth, g.typeName(t), lhs,
			k, v, lhs, kc, vc, depth, k, v, lhs, depth) + g.mapKeys(lhs, t) + "}\n"
	case *gotypes.Interface:
		return fmt.Sprintf("%s = c.cloneAny(%s)\n", lhs, lhs)
	case *gotypes.Array:
		inner := g.value(fmt.Sprintf("%s[i%d]", lhs, depth), t.Elem(), depth+1)
		if inner == "" {
			return ""
		}
		return fmt.Sprintf("for i%d := range %s {\n%s}\n", depth, lhs, inner)
	case *gotypes.Named:
		n, ok := g.local(t)
		if !ok {
			return ""
		}
		switch u := n.Underlying().(type) {
		case *gotypes.Struct:
			if g.hasDeep(n, map[*gotypes.Named]bool{}) {
				return fmt.Sprintf("c.fix%s(&%s)\n", n.Obj().Name(), lhs)
			}
			return ""
		case *gotypes.Interface:
			return fmt.Sprintf("%s = c.clone%s(%s)\n", lhs, n.Obj().Name(), lhs)
		default:
			return g.value(lhs, u, depth)
		}
	}
	panic("clone: unhandled type " + t.String())
}

func (g *cloneGen) mapKeys(lhs string, t *gotypes.Map) string {
	if _, ok := gotypes.Unalias(t.Key()).(*gotypes.Interface); ok {
		return fmt.Sprintf("c.keys = append(c.keys, &%s)\n", lhs)
	}
	return ""
}

// hasDeep reports whether a struct of type n has a field that a copy
// must make its own.
func (g *cloneGen) hasDeep(n *gotypes.Named, seen map[*gotypes.Named]bool) bool {
	if seen[n] {
		return false
	}
	seen[n] = true
	s := n.Underlying().(*gotypes.Struct)
	for i := range s.NumFields() {
		switch ft := gotypes.Unalias(s.Field(i).Type()).(type) {
		case *gotypes.Basic:
		case *gotypes.Named:
			if m, ok := g.local(ft); ok {
				switch m.Underlying().(type) {
				case *gotypes.Struct:
					if g.hasDeep(m, seen) {
						return true
					}
				case *gotypes.Basic:
				default:
					return true
				}
			}
		default:
			return true
		}
	}
	return false
}

// iface writes clone<I>, which copies the node an interface holds.
func (g *cloneGen) iface(n *gotypes.Named) {
	name := n.Obj().Name()
	fmt.Fprintf(&g.b, "func (c *cloner) clone%s(x %s) %s {\n\tswitch x := x.(type) {\n\tcase nil:\n\t\treturn nil\n", name, name, name)
	for _, s := range g.impls(n.Underlying().(*gotypes.Interface)) {
		fmt.Fprintf(&g.b, "\tcase *%s:\n\t\treturn c.clone%s(x)\n", s.Obj().Name(), s.Obj().Name())
	}
	fmt.Fprintf(&g.b, "\t}\n\tpanic(fmt.Sprintf(\"syntax: Clone: unknown %s %%T\", x))\n}\n\n", name)
}
