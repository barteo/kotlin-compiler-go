#!/bin/sh
# Compares the speed of the code kc writes with the code kotlinc writes:
# compiles bench/runtime/Bench.kt with each, runs both builds on the same
# JVM, and writes bench/results/runtime.md.
#
#   bench/runtime.sh                        # about 1 minute
#   FORKS=10 ROUNDS=40 bench/runtime.sh
#
# FORKS: JVMs started per build, alternating between the builds (default
# 5). WARMUP and ROUNDS: untimed and timed rounds of each workload in each
# JVM (default 10 and 20). Each workload's time is the median over the
# forks of each fork's median round. JVM_OPTS: options for the JVMs that
# run the benchmark (default a fixed 1 GB heap).
#
# Needs: go, java (JDK 21), kotlinc, python3.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
: "${TMPDIR:=/tmp}"
work="$TMPDIR/kc-runtime"
results="$root/bench/results"
forks=${FORKS:-5}
warmup=${WARMUP:-10}
rounds=${ROUNDS:-20}
jvm_opts=${JVM_OPTS:-"-Xms1g -Xmx1g"}
kotlin_home=${KOTLIN_HOME:-/opt/homebrew/opt/kotlin/libexec}
stdlib="$kotlin_home/lib/kotlin-stdlib.jar"
brew_jdk=/opt/homebrew/opt/openjdk@21/libexec/openjdk.jdk/Contents/Home
if [ -z "${JAVA_HOME:-}" ] && [ -d "$brew_jdk" ]; then
	export JAVA_HOME="$brew_jdk"
fi
[ -n "${JAVA_HOME:-}" ] && export PATH="$JAVA_HOME/bin:$PATH"
[ -f "$stdlib" ] || { echo "no $stdlib: set KOTLIN_HOME to kotlinc's home"; exit 1; }

rm -rf "$work"
mkdir -p "$work/runs" "$results"
(cd "$root" && go build -o "$work/kc" ./cmd/kc)
"$work/kc" -cp "$stdlib" -d "$work/out-kc" "$root/bench/runtime/Bench.kt"
kotlinc -nowarn -d "$work/out-kotlinc" "$root/bench/runtime/Bench.kt" 2>&1 | grep -v JAVA_TOOL_OPTIONS || true
[ -f "$work/out-kotlinc/BenchKt.class" ] || { echo "kotlinc failed"; exit 1; }

i=1
while [ "$i" -le "$forks" ]; do
	for c in kc kotlinc; do
		echo "fork $i/$forks: $c"
		# shellcheck disable=SC2086 # the options are words
		java $jvm_opts -cp "$work/out-$c:$stdlib" BenchKt "$warmup" "$rounds" 2>/dev/null >"$work/runs/$c-$i.tsv"
	done
	i=$((i + 1))
done

out="$results/runtime.md"
{
	echo "# Speed of the generated code: kc vs kotlinc"
	echo
	echo "\`bench/runtime/Bench.kt\` compiled by each compiler, run with the same"
	echo "Kotlin standard library on the same JVM. Generated by \`bench/runtime.sh\`."
	echo
	echo "- Machine: $(uname -sm), $(getconf _NPROCESSORS_ONLN) CPUs"
	echo "- $(java -version 2>&1 | grep -v JAVA_TOOL | head -1)"
	echo "- $(kotlinc -version 2>&1 | grep -v JAVA_TOOL | tail -1)"
	echo "- JVM options: $jvm_opts"
	echo "- $forks JVMs per build, each running $warmup warmup and $rounds timed rounds of each workload"
	echo
	python3 - "$work/runs" "$forks" <<'PY'
import statistics, sys
runs, forks = sys.argv[1], int(sys.argv[2])
times, sums, order = {}, {}, []
for c in ("kc", "kotlinc"):
    for i in range(1, forks + 1):
        for line in open(f"{runs}/{c}-{i}.tsv"):
            name, ms, check = line.split("\t")
            if name not in order:
                order.append(name)
            times.setdefault((c, name), []).append(float(ms))
            sums.setdefault(name, set()).add(check.strip())
print("Median milliseconds per round (lower is better). Ratio above 1: kc's code is slower.")
print()
print("| Workload | `kotlinc` | `kc` | kc / kotlinc |")
print("|:---|---:|---:|---:|")
ratios, bad = [], []
for name in order:
    k = statistics.median(times[("kotlinc", name)])
    g = statistics.median(times[("kc", name)])
    ratios.append(g / k)
    if len(sums[name]) != 1:
        bad.append(name)
    print(f"| {name} | {k:.2f} | {g:.2f} | {g / k:.2f} |")
print(f"| **Geometric mean** | | | **{statistics.geometric_mean(ratios):.2f}** |")
print()
print("- Same checksums: " + ("yes" if not bad else "NO: " + ", ".join(bad)))
PY
} >"$out"
cat "$out"
