// GenStubs writes Stubs.kt: for each Analysis API class or interface named
// on the command line, an abstract class Stub<Name> that implements every
// abstract member by throwing UnsupportedOperationException("kc: ...").
// kc's implementations extend the stubs and override what they support, so
// the members a client reaches that kc lacks fail with their names.
//
//	GenStubs OUT.kt fq.Name...
import java.io.File
import kotlin.reflect.KClass
import kotlin.reflect.KFunction
import kotlin.reflect.KMutableProperty
import kotlin.reflect.KParameter
import kotlin.reflect.KProperty
import kotlin.reflect.KType
import kotlin.reflect.KVisibility
import kotlin.reflect.full.isSuperclassOf

fun main(args: Array<String>) {
    val sb = StringBuilder()
    sb.append("// Code generated by jvm/kc-aa/gen/GenStubs.kt. DO NOT EDIT.\n")
    sb.append("@file:Suppress(\"DEPRECATION\", \"OVERRIDE_DEPRECATION\", \"DEPRECATION_ERROR\", \"PLATFORM_CLASS_MAPPED_TO_KOTLIN\")\n\n")
    sb.append("package io.github.barteo.kc.aa\n\n")
    for (name in args.drop(1)) {
        val k = Class.forName(name).kotlin
        stub(sb, k)
    }
    File(args[0]).writeText(sb.toString())
}

fun type(t: KType): String = t.toString()
    .replace(Regex("""\(Kotlin reflection is not available\)"""), "")
    .replace("!", "")

fun stub(sb: StringBuilder, k: KClass<*>) {
    val simple = k.simpleName!!
    val qn = k.qualifiedName!!
    val tps = k.typeParameters
    val tpDecl = if (tps.isEmpty()) "" else tps.joinToString(", ", "<", ">") { tp ->
        val b = tp.upperBounds.filter { it.toString() != "kotlin.Any?" }
        tp.name + (if (b.size == 1) " : " + type(b[0]) else "")
    }
    val tpUse = if (tps.isEmpty()) "" else tps.joinToString(", ", "<", ">") { it.name }
    val sup = if (k.java.isInterface) "$qn$tpUse" else "$qn$tpUse()"
    sb.append("abstract class Stub$simple$tpDecl : $sup {\n")
    for (m in k.members.sortedBy { it.name + it.parameters.size }) {
        if (!m.isAbstract || m.visibility == KVisibility.PRIVATE || m.visibility == KVisibility.INTERNAL) continue
        val what = "\"kc: $simple.${m.name}\""
        val ext = m.parameters.firstOrNull { it.kind == KParameter.Kind.EXTENSION_RECEIVER }
        val recv = if (ext != null) type(ext.type) + "." else ""
        when (m) {
            is KMutableProperty<*> -> {
                sb.append("    override var $recv${q(m.name)}: ${type(m.returnType)}\n")
                sb.append("        get() = throw UnsupportedOperationException($what)\n")
                sb.append("        set(_) = throw UnsupportedOperationException($what)\n")
            }
            is KProperty<*> ->
                sb.append("    override val $recv${q(m.name)}: ${type(m.returnType)} get() = throw UnsupportedOperationException($what)\n")
            is KFunction<*> -> {
                val ftp = m.typeParameters
                val ftpDecl = if (ftp.isEmpty()) "" else ftp.joinToString(", ", "<", "> ") { tp ->
                    val b = tp.upperBounds.filter { it.toString() != "kotlin.Any?" }
                    tp.name + (if (b.size == 1) " : " + type(b[0]) else "")
                }
                val ps = m.parameters.filter { it.kind == KParameter.Kind.VALUE }
                    .joinToString(", ") { (if (it.isVararg) "vararg " else "") + "${q(it.name ?: "p${it.index}")}: ${type(if (it.isVararg) it.type.arguments[0].type!! else it.type)}" }
                val mods = (if (m.isOperator) "operator " else "") + (if (m.isInfix) "infix " else "")
                sb.append("    override ${mods}fun $ftpDecl$recv${q(m.name)}($ps): ${type(m.returnType)} = throw UnsupportedOperationException($what)\n")
            }
        }
    }
    sb.append("}\n\n")
}

val keywords = setOf("in", "is", "as", "fun", "val", "var", "object", "typealias", "when", "interface", "package", "class", "this", "super", "null", "true", "false", "throw", "return", "try", "while", "do", "if", "else", "for", "break", "continue", "typeof")
fun q(n: String) = if (n in keywords) "`$n`" else n
